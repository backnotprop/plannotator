/**
 * schema/wire.schema.json: JSON Schema (2020-12) for every wire type a client
 * reads or sends, made from the product's own TypeScript by the TypeScript
 * compiler. One file, every type under `$defs`, so a test reads one known
 * path and never lists a folder.
 *
 *   bun scripts/mobile/schema.ts [--check]
 *
 * ROOTS names the types; every type they reach comes too. Rules, so an old app
 * keeps reading a newer Inbox: every object allows unknown fields
 * (`additionalProperties: true`); every enum is open (`x-open`: a reader keeps
 * a value it does not know); a field the TypeScript marks optional is not
 * required. swift.ts turns this file into Swift.
 *
 * Doc comments are not copied: a comment-only edit to a wire type changes no
 * generated byte (and starts no iPhone job). A number is an `integer` when its
 * field's name says it counts or orders (INTEGER_NAME: seqs, cursors,
 * revisions, sizes, counts, totals, offsets, limits, positions, milliseconds); Wire.swift reads those
 * as Int64, every other number as Double.
 *
 * The compiler is the TypeScript 5.8 that packages/core builds with (the root's
 * TypeScript 7 has no compiler API); it reads only, through its own file
 * reads, and takes about a third of a second. A compiler error in what it
 * reads stops it: a broken import must never become an untyped field.
 */
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { OUT, ROOT, cli, jsonText, type Output } from './lib';

// The literal list of what the compiler reads, generated below: importing it lets the picker see every source.
export { SCHEMA_SOURCES } from './schema-sources';

/** The files the roots are in, and the root types of each. */
export const ROOTS: Record<string, string[]> = {
  'packages/core/inbox-types.ts': [
    'InboxHealth', 'InboxListRow', 'InboxListSection', 'InboxThread', 'InboxMessageWire', 'InboxQuestion', 'InboxProject',
    'InboxDelivery', 'InboxRun', 'InboxRecordKind', 'InboxSectionId', 'InboxQuestionState', 'InboxUpload', 'InboxDraft',
  ],
  'packages/core/question-block.ts': ['QuestionAnswer'],
  'packages/core/inbox-door-version.ts': ['InboxDoorHealth'],
  'packages/shared/inbox/devices.ts': ['InboxDevicePublic'],
  'packages/core/inbox-wire-models.ts': ['ListModel', 'ThreadModel', 'ReplyResult', 'ArchivedModel'],
  'scripts/mobile/door-shapes.ts': [
    'DoorError', 'DoorPairRequest', 'DoorPairAnswer', 'DoorRevokeAnswer', 'DoorHelloFrame', 'DoorRecordFrame', 'DoorSeenBody',
    'DoorPicksBody', 'DoorPicksAnswer', 'DoorReplyBody',
    'DoorResolveBody', 'DoorKeyBody', 'DoorMarkUnreadAnswer', 'DoorPinBody', 'DoorPinsBody',
    'DoorSnoozeBody', 'DoorSnoozeAnswer', 'DoorPriorityBody', 'DoorPriorityAnswer', 'DoorThreadDraftAnswer', 'DoorThreadAttachmentsAnswer', 'DoorAnnotationBody', 'DoorAnnotationAnswer', 'DoorAnnotationRemoveBody', 'DoorMarkupAnswer',
  ],
};


/** A number field whose name says it counts or orders: an `integer` (Int64 in Swift). */
export const INTEGER_NAME = /(^|_)(seq|cursor|revision|rev|ms|bytes|size|count|position|total|offset|limit)$/;

export type Schema = Record<string, unknown>;

/** Generic helpers whose instantiation is an object of its own, not a named type. */
const UTILITY = new Set(['Omit', 'Pick', 'Partial', 'Required', 'Readonly', 'Record', 'Exclude', 'Extract', 'NonNullable']);

/* The compiler's API is untyped here: the root's `typescript` package is version 7, with no API types. */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Any = any;

function compiler(): Any {
  return createRequire(join(ROOT, 'packages/core/package.json'))('typescript');
}

let built: Schema | undefined;
/** The repository files the compiler read for the last schema made. */
let reads: string[] = [];

/** The schema (made once per process: door, surface and vectors all read it). */
export function buildSchema(): Schema {
  built ??= makeSchema();
  return built;
}

/**
 * The schema as it would be with some files' text replaced (`overrides`: path from the root to text). For the
 * tests: a doc-comment edit must change no byte.
 */
export function schemaWith(overrides: Record<string, string>): Schema {
  return makeSchema(overrides);
}

function makeSchema(overrides: Record<string, string> = {}): Schema {
  const ts = compiler();
  const files = Object.keys(ROOTS).map((f) => join(ROOT, f));
  const options = {
    strict: true, noEmit: true, skipLibCheck: true, types: ['node'], target: ts.ScriptTarget.ESNext,
    module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, jsx: ts.JsxEmit.ReactJSX,
  };
  const host = ts.createCompilerHost(options);
  const replaced = new Map(Object.entries(overrides).map(([path, text]) => [join(ROOT, path), text]));
  if (replaced.size) {
    const read = host.readFile.bind(host);
    host.readFile = (file: string) => replaced.get(file) ?? read(file);
    const get = host.getSourceFile.bind(host);
    host.getSourceFile = (file: string, language: Any, ...rest: Any[]) => {
      const text = replaced.get(file);
      return text === undefined ? get(file, language, ...rest) : ts.createSourceFile(file, text, language, true);
    };
  }
  const program = ts.createProgram(files, options, host);
  const problems = [
    ...program.getOptionsDiagnostics(), ...program.getGlobalDiagnostics(),
    ...files.flatMap((f) => [...program.getSyntacticDiagnostics(program.getSourceFile(f)), ...program.getSemanticDiagnostics(program.getSourceFile(f))]),
  ];
  if (problems.length) {
    const lines = problems.map((d: Any) => `  ${d.file ? `${d.file.fileName.slice(ROOT.length + 1)}: ` : ''}${ts.flattenDiagnosticMessageText(d.messageText, ' ')}`);
    throw new Error(`schema.ts: the compiler reports errors in the wire types:\n${lines.join('\n')}`);
  }
  const read = (program.getSourceFiles() as Any[])
    .map((f) => f.fileName as string)
    .filter((f) => f.startsWith(`${ROOT}/`) && !f.includes('/node_modules/'))
    .map((f) => f.slice(ROOT.length + 1))
    .sort();
  if (Object.keys(overrides).length === 0) reads = read;
  const checker = program.getTypeChecker();
  const defs = new Map<string, Schema>();
  const sources = new Map<string, string>();

  const sourceOf = (symbol: Any): string | undefined => {
    const file: string | undefined = symbol?.declarations?.[0]?.getSourceFile?.().fileName;
    return file?.startsWith(`${ROOT}/`) ? file.slice(ROOT.length + 1) : undefined;
  };

  /** The name a type is kept under in `$defs`, or null to write it in place. */
  const nameOf = (type: Any): string | null => {
    const alias = type.aliasSymbol;
    if (alias && !UTILITY.has(alias.name)) {
      const args: Any[] = type.aliasTypeArguments ?? [];
      return args.length ? null : alias.name;
    }
    const symbol = type.symbol;
    if (symbol && symbol.flags & (ts.SymbolFlags.Interface | ts.SymbolFlags.Class) && !(type.objectFlags & ts.ObjectFlags.Reference && type.typeArguments?.length)) {
      return symbol.name;
    }
    return null;
  };

  const isNull = (t: Any) => (t.flags & ts.TypeFlags.Null) !== 0;
  const isUndefined = (t: Any) => (t.flags & (ts.TypeFlags.Undefined | ts.TypeFlags.Void)) !== 0;

  const convert = (type: Any): Schema => {
    const f = type.flags;
    if (f & (ts.TypeFlags.Any | ts.TypeFlags.Unknown | ts.TypeFlags.TypeParameter | ts.TypeFlags.Never)) return {};
    if (f & ts.TypeFlags.StringLiteral) return { type: 'string', const: type.value };
    if (f & ts.TypeFlags.NumberLiteral) return { type: 'number', const: type.value };
    if (f & ts.TypeFlags.BooleanLiteral) return { type: 'boolean', const: type.intrinsicName === 'true' };
    if (f & (ts.TypeFlags.String | ts.TypeFlags.TemplateLiteral | ts.TypeFlags.StringMapping)) return { type: 'string' };
    if (f & (ts.TypeFlags.Number | ts.TypeFlags.BigInt)) return { type: 'number' };
    if (f & ts.TypeFlags.Boolean) return { type: 'boolean' };
    if (f & ts.TypeFlags.Null) return { type: 'null' };
    if (f & ts.TypeFlags.Union) return named(type, () => union(type));
    if (f & ts.TypeFlags.Intersection) {
      const prim = (type.types as Any[]).find((t) => t.flags & (ts.TypeFlags.String | ts.TypeFlags.Number | ts.TypeFlags.Boolean));
      if (prim) return convert(prim);
      return named(type, () => object(type));
    }
    if (f & ts.TypeFlags.Object) {
      if (checker.isArrayType(type) || checker.isTupleType(type)) {
        const args: Any[] = checker.getTypeArguments(type);
        if (checker.isTupleType(type)) return { type: 'array', items: args.length ? anyOf(args.map(convert)) : {} };
        return { type: 'array', items: convert(args[0]) };
      }
      if (checker.getSignaturesOfType(type, ts.SignatureKind.Call).length && !checker.getPropertiesOfType(type).length) return {};
      return named(type, () => object(type));
    }
    return {};
  };

  const anyOf = (parts: Schema[]): Schema => {
    const seen = new Map<string, Schema>();
    for (const p of parts) seen.set(JSON.stringify(p), p);
    const list = [...seen.values()];
    return list.length === 1 ? list[0]! : { anyOf: list };
  };

  const union = (type: Any): Schema => {
    const members: Any[] = (type.types as Any[]).filter((t) => !isUndefined(t));
    const nullable = members.some(isNull);
    const rest = members.filter((t) => !isNull(t));
    let body: Schema;
    const bools = rest.filter((t) => t.flags & ts.TypeFlags.BooleanLiteral);
    const others = bools.length === 2 ? rest.filter((t) => !(t.flags & ts.TypeFlags.BooleanLiteral)) : rest;
    const parts: Schema[] = bools.length === 2 ? [{ type: 'boolean' }] : [];
    const strings = others.filter((t) => t.flags & ts.TypeFlags.StringLiteral);
    const openString = others.some((t) => t.flags & (ts.TypeFlags.String | ts.TypeFlags.TemplateLiteral));
    if (strings.length && !openString) parts.push({ type: 'string', enum: strings.map((t) => t.value as string).sort(), 'x-open': true });
    const numbers = others.filter((t) => t.flags & ts.TypeFlags.NumberLiteral);
    if (numbers.length) parts.push({ type: 'number', enum: numbers.map((t) => t.value as number).sort((a, b) => a - b) });
    for (const t of others) if (!(t.flags & (ts.TypeFlags.StringLiteral | ts.TypeFlags.NumberLiteral))) parts.push(convert(t));
    body = parts.length === 0 ? {} : anyOf(parts);
    if (nullable) body = rest.length ? { anyOf: [...((body.anyOf as Schema[] | undefined) ?? [body]), { type: 'null' }] } : { type: 'null' };
    return body;
  };

  const object = (type: Any): Schema => {
    const properties: Record<string, Schema> = {};
    const required: string[] = [];
    for (const prop of checker.getPropertiesOfType(type) as Any[]) {
      const decl = prop.valueDeclaration ?? prop.declarations?.[0];
      const propType = decl ? checker.getTypeOfSymbolAtLocation(prop, decl) : checker.getTypeOfSymbol(prop);
      if (checker.getSignaturesOfType(propType, ts.SignatureKind.Call).length && !(propType.flags & ts.TypeFlags.Union)) continue;
      const schema = { ...convert(propType) };
      properties[prop.name] = INTEGER_NAME.test(prop.name) ? integer(schema) : schema;
      const optional = (prop.flags & ts.SymbolFlags.Optional) !== 0 || (propType.flags & ts.TypeFlags.Union && (propType.types as Any[]).some(isUndefined));
      if (!optional) required.push(prop.name);
    }
    const out: Schema = { type: 'object', properties };
    if (required.length) out.required = required;
    const index = checker.getIndexInfosOfType(type) as Any[];
    const byString = index.find((i) => i.keyType.flags & ts.TypeFlags.String);
    out.additionalProperties = byString ? convert(byString.type) : true;
    return out;
  };

  /** `number` made `integer`, also inside a nullable or a list. */
  const integer = (schema: Schema): Schema => {
    if (schema.type === 'number' && schema.enum === undefined && schema.const === undefined) return { ...schema, type: 'integer' };
    if (Array.isArray(schema.anyOf)) return { ...schema, anyOf: (schema.anyOf as Schema[]).map(integer) };
    if (schema.type === 'array' && schema.items) return { ...schema, items: integer(schema.items as Schema) };
    return schema;
  };

  /** A named type goes to `$defs` once (recursion meets the placeholder); an unnamed one is written in place. */
  const named = (type: Any, build: () => Schema): Schema => {
    const name = nameOf(type);
    if (!name) return build();
    const symbol = type.aliasSymbol ?? type.symbol;
    const at = sourceOf(symbol);
    const key = `${at ?? ''}#${name}`;
    const known = sources.get(name);
    if (known !== undefined && known !== key) throw new Error(`schema.ts: two types named ${name} (${known}, ${key})`);
    if (!defs.has(name)) {
      sources.set(name, key);
      defs.set(name, {});
      const body = build();
      defs.set(name, { ...body, ...(at ? { 'x-source': at } : {}) });
    }
    return { $ref: `#/$defs/${name}` };
  };

  const roots: Record<string, string> = {};
  for (const [file, names] of Object.entries(ROOTS)) {
    const source = program.getSourceFile(join(ROOT, file));
    if (!source) throw new Error(`schema.ts: cannot read ${file}`);
    const exports: Any[] = checker.getExportsOfModule(checker.getSymbolAtLocation(source));
    for (const name of names) {
      let symbol = exports.find((s) => s.name === name);
      if (!symbol) throw new Error(`schema.ts: ${file} exports no ${name}`);
      if (symbol.flags & ts.SymbolFlags.Alias) symbol = checker.getAliasedSymbol(symbol);
      const type = checker.getDeclaredTypeOfSymbol(symbol);
      const ref = convert(type);
      if (ref.$ref !== `#/$defs/${name}`) {
        // A root that is an instantiation (`Omit<…>`) or a plain alias: kept under its own name.
        defs.set(name, { ...ref, 'x-source': file });
        sources.set(name, `${file}#${name}`);
      }
      roots[name] = file;
    }
  }

  const sorted = Object.fromEntries([...defs.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: 'https://plannotator.ai/contract/wire.schema.json',
    about: 'GENERATED by scripts/mobile/schema.ts from the product TypeScript named in `roots`. Do not edit.',
    roots: Object.fromEntries(Object.entries(roots).sort(([a], [b]) => (a < b ? -1 : 1))),
    $defs: sorted,
  };
}

export const SOURCES_FILE = 'scripts/mobile/schema-sources.ts';

/**
 * The schema, and SCHEMA_SOURCES (schema-sources.ts): every repository file the compiler reads for it, as literals,
 * so scripts/ci-affected.ts selects the contract's test when one changes, whatever its import scan sees. A wire type
 * that starts importing a new file leaves schema-sources.ts stale, and the one command writes it.
 */
export function generateSchema(): Output[] {
  const schema = buildSchema();
  const sources = [
    '/**',
    ' * GENERATED by scripts/mobile/schema.ts (bun scripts/mobile/all.ts). Do not edit.',
    ' * Every repository file the compiler reads for the wire schema, as literals, so',
    ' * scripts/ci-affected.ts selects the contract\'s test when one changes.',
    ' */',
    'export const SCHEMA_SOURCES = [',
    ...reads.map((f) => `  '${f}',`),
    '] as const;',
    '',
  ].join('\n');
  return [{ path: OUT.schema, text: jsonText(schema) }, { path: SOURCES_FILE, text: sources }];
}

if (import.meta.main) cli('schema', generateSchema);
