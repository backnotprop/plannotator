const TIME_SCRIPT = 'scripts/mobile/vectors-time.ts';

const about = (what: string, from: string) =>
  `GENERATED by scripts/mobile/vectors.ts from ${from}. Do not edit. ${what}`;

type FixtureRow = InboxSectionFacts & { thread_id: string; note: string; last_at: string };

/** Rows to the Inbox's sections, each row's bold, the drawn order and the badge. */
export function listVectors(): unknown {
  const fixture = JSON.parse(readRepoText(FIXTURES.list)) as { rows: FixtureRow[] };
  const rows = fixture.rows.map((row) => {
    const section = inboxSectionOf(row);
    const draftOnly = inboxRowDraftOnly(section, row.unseen, row.answered_not_sent, row.unsent);
    return { row, section, unread: inboxRowUnread(section, row.unseen, draftOnly) };
  });
  const listRows = rows.map(({ row, section }) => ({ ...row, section }) as unknown as InboxListRow);
  const sections = inboxListSections(listRows);
  const count = inboxTabCount(sections);
  return {
    about: about('Each row: its section and whether it is bold. Then every section in order with its thread ids, and the badge (the window\'s tab count).', FIXTURES.list),
    rows: rows.map(({ row, section, unread }) => ({ thread_id: row.thread_id, note: row.note, section, unread })),
    sections: sections.map((s) => ({ id: s.id, label: s.label, threads: s.threads.map((t) => t.thread_id) })),
    badge: { count, label: tabBadgeLabel(count) },
  };
}

/** Each word of words.json with sample parts, and the counting words, as the product's functions print them. */
export function wordVectors(): unknown {
  const words = buildWords();
  const name = 'Claude Code';
  const filled = (key: string, made: string, parts: Record<string, string | number>) => {
    const word = words[key];
    if (!word) throw new Error(`vectors.ts: no word ${key}`);
    return { key, parts, text: made };
  };
  return {
    about: about('Each template filled with sample parts, as the window prints it; then the counting words.', 'the product\'s word functions'),
    filled: [
      filled('delivery.sent_queued', sentRowLine(name, true), { name }),
      filled('delivery.sent_saved', sentRowLine(name, false), { name }),
      filled('delivery.reask_waiting', reaskRowLine(name, '2026-11-18T09:00:00.000Z', true), { name }),
      filled('delivery.reask_queued', reaskRowLine(name, null, true), { name }),
      filled('delivery.reask_saved', reaskRowLine(name, null, false), { name }),
      filled('delivery.auto_after', autoAfterText(5), { minutes: 5 }),
    ],
    counts: [0, 1, 2, 9, 1284].map((n) => ({
      n,
      formatCount: formatCount(n),
      questionCount: questionCount(n),
      waitCount: waitCount(n),
      waitCountWithOneAction: waitCount(n, 1),
      pluralThread: plural(n, 'thread'),
    })),
  };
}

/** The time words in each of the fixture's zones, each from its own process with TZ set. */
export function timeVectors(): unknown {
  const fixture = JSON.parse(readRepoText(FIXTURES.time)) as { time_zones: string[]; now: string };
  const zones = fixture.time_zones.map((zone) => {
    const run = Bun.spawnSync([process.execPath, TIME_SCRIPT], { cwd: ROOT, env: { ...process.env, TZ: zone }, stdout: 'pipe', stderr: 'pipe' });
    if (run.exitCode !== 0) throw new Error(`vectors.ts: ${TIME_SCRIPT} failed in ${zone}: ${run.stderr.toString()}`);
    const made = JSON.parse(run.stdout.toString()) as { time_zone: string; cases: Record<string, string>[] };
    if (made.time_zone !== zone) throw new Error(`vectors.ts: ${TIME_SCRIPT} ran in ${made.time_zone}, not ${zone}`);
    return made;
  });
  // iOS's en_US time format puts U+202F (narrow no-break space) before AM and PM; the window prints U+0020.
  const ios = (text: string) => text.replace(/ (AM|PM)\b/g, '\u202f$1');
  const examples = [...new Set(zones.flatMap((z) => z.cases.flatMap((c) => Object.entries(c).filter(([k]) => k !== 'iso').map(([, v]) => v))).filter((v) => / (AM|PM)\b/.test(v)))]
    .sort()
    .slice(0, 6)
    .map((window) => ({ ios: ios(window), window }));
  return {
    about: about('Per time zone: the app formats in the zone it is given (never UTC unless told) and must give the same words.', FIXTURES.time),
    normalise: {
      rule: 'Before comparing, replace U+202F (narrow no-break space) and U+00A0 (no-break space) with U+0020. iOS formats en_US times with U+202F before AM and PM; the window prints U+0020.',
      examples,
    },
    now: fixture.now,
    zones,
  };
}

/**
 * The relay's collapse id for each thread of the relay vectors, under the
 * collapse key the product derives from the same all-zero inputs. The key
 * itself is not written here: the app derives it (its HKDF label is in
 * packages/core/crypto.ts) and must reach these ids. The HMAC step is the
 * Inbox's own (packages/server/inbox-relay.ts, the push's collapse id).
 */
export async function cryptoVectors(): Promise<unknown> {
  const relay = JSON.parse(readRepoText(FIXTURES.relay)) as { pairing_secret: string; device_id: string; derived: Record<string, string>; envelopes: { plaintext: string }[] };
  const keys = await deriveRelayKeys(relay.pairing_secret, relay.device_id);
  if (keys.key !== relay.derived.key || keys.upKey !== relay.derived.up_key || keys.relaySecret !== relay.derived.relay_secret) {
    throw new Error(`vectors.ts: ${FIXTURES.relay} no longer matches deriveRelayKeys`);
  }
  const threadOf = (plaintext: string): string | null => {
    try {
      const id = (JSON.parse(plaintext) as { thread_id?: unknown }).thread_id;
      return typeof id === 'string' ? id : null;
    } catch {
      return null; // a plaintext that is not JSON (the vectors seal plain text too)
    }
  };
  const threads = [...new Set([...relay.envelopes.map((e) => threadOf(e.plaintext)).filter((t): t is string => t !== null), 'msg_A00000000000000000000001'])];
  return {
    about: about('The keys, envelopes and inputs are in the relay vectors file named in "relay_vectors"; this adds the push collapse id.', FIXTURES.relay),
    relay_vectors: FIXTURES.relay,
    collapse: {
      hkdf_info: 'plannotator-inbox relay collapse v1',
      hmac: 'sha256 over the thread id, keyed by the collapse key (base64url-decoded); hex',
      ids: threads.map((thread_id) => ({ thread_id, collapse_id: createHmac('sha256', Buffer.from(keys.collapseKey, 'base64url')).update(thread_id).digest('hex') })),
    },
  };
}

type Act = { question: string; note?: string; unsentOnly?: boolean; confirmFull?: boolean } & (
  | { act: 'choice'; selected: string[] }
  | { act: 'other'; other: string }
  | { act: 'text'; text: string }
  | { act: 'skip' }
  | { act: 'clear' }
);

/** Each act on a question: the answer the window's builders make, and the pick body that saves it (null: taken back). */
export function questionVectors(): unknown {
  const fixture = JSON.parse(readRepoText(FIXTURES.questions)) as { questions: InboxQuestion[]; acts: Act[] };
  const byKey = new Map(fixture.questions.map((q) => [q.key, q]));
  return {
    about: about('Each act: the answer the window builds (packages/core/inbox-answers.ts) and the body POST messages/:id/picks takes, at the question\'s revision. The door adds idempotency_key.', FIXTURES.questions),
    cases: fixture.acts.map((act) => {
      const q = byKey.get(act.question);
      if (!q) throw new Error(`vectors.ts: no question ${act.question}`);
      const note = act.note ?? '';
      const answer =
        act.act === 'choice' ? choiceAnswer(q, act.selected, note)
        : act.act === 'other' ? otherAnswer(q, act.other, note)
        : act.act === 'text' ? textAnswer(q, act.text, note)
        : act.act === 'skip' ? skipAnswer(q, note)
        : null;
      return { act, message_id: q.message_id, answer, body: inboxPickBody(q.key, q.revision, answer, { unsentOnly: act.unsentOnly, confirmFull: act.confirmFull }) };
    }),
  };
}

type SkewCase = { note: string; client: string; health: unknown };

/** Health answers read by the door's own rules (what the app offers), and app headers as the door parses them. */
export function skewVectors(): unknown {
  const fixture = JSON.parse(readRepoText(FIXTURES.skew)) as {
    clients: Record<string, InboxDoorClient>; routes: string[]; health: SkewCase[];
    big_contract: { note: string; client: string; health_text: string }; headers: string[];
  };
  const read = ({ note, client, health }: SkewCase, text?: string) => {
    const c = fixture.clients[client];
    if (!c) throw new Error(`vectors.ts: no client ${client}`);
    const skew = readInboxDoorHealth(health, c);
    return {
      note, client, ...(text === undefined ? { health } : { health_text: text }), skew,
      offers: fixture.routes.map((route) => ({ route, direct: inboxDoorOffers(skew, route, 'direct'), relay: inboxDoorOffers(skew, route, 'relay') })),
    };
  };
  const big = fixture.big_contract;
  return {
    about: about('Each health answer as the app reads it (readInboxDoorHealth) and which routes it then offers, directly and through the relay (inboxDoorOffers); then each X-Plannotator-App header as the door parses it (null: read as no header).', FIXTURES.skew),
    clients: fixture.clients,
    health: [...fixture.health.map((h) => read(h)), read({ note: big.note, client: big.client, health: JSON.parse(big.health_text) }, big.health_text)],
    headers: fixture.headers.map((header) => {
      const app = parseInboxAppHeader(header);
      return { header, app, formatted: app ? formatInboxAppHeader(app) : null };
    }),
  };
}

export async function generateVectors(): Promise<Output[]> {
  return [
    { path: VECTORS.list, text: jsonText(listVectors()) },
    { path: VECTORS.words, text: jsonText(wordVectors()) },
    { path: VECTORS.time, text: jsonText(timeVectors()) },
    { path: VECTORS.crypto, text: jsonText(await cryptoVectors()) },
    { path: VECTORS.questions, text: jsonText(questionVectors()) },
    { path: VECTORS.skew, text: jsonText(skewVectors()) },
  ];
}

if (import.meta.main) await cli('vectors', generateVectors);
