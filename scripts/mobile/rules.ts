/**
 * The generators' own rules, checked on the live product (docs/agent-guides/mobile.md). Each reads a table only the
 * mobile scripts keep (door.ts's collections and byte routes, words.ts's templates, schema.ts's roots), so an Inbox
 * change can break one for a phone's reason. That is why they run here, from scripts/mobile/check.ts in the
 * mobile-contract workflow, and never in a unit lane. The door table itself (doorRouteTable, doorReachOf) is the
 * Inbox's, held by packages/server/inbox-door-version.test.ts and inbox-outbox.test.ts.
 *
 * Each returns the lines a person acts on; empty: it holds.
 */
import { isDeepStrictEqual } from 'node:util';
import { autoAfterText, reaskRowLine, sentRowLine } from '../../packages/core/inbox-delivery-line';
import { INBOX_SECTIONS } from '../../packages/core/inbox-types';
import { MACHINE_PLATFORM, doorReachOf, doorRouteOf } from '../../packages/server/inbox-devices';
import { doorEntries } from './door';
import { readRepoText } from './lib';
import { buildSchema, schemaWith } from './schema';
import { buildWords } from './words';

const same = (a: unknown, b: unknown) => isDeepStrictEqual(a, b);
const sample = (path: string) => path.replace(/\{path\}/g, 'a/b.png').replace(/\{card\}/g, 'crd_x').replace(/\{combine\}/g, 'cmb_x').replace(/\{action\}/g, 'a-0123abcd').replace(/\{\w+\}/g, 'x_1');

/** door.json is the door: health lists its routes, each reaches the door for the token it names, a write has its key. */
export function doorRules(): string[] {
  const bad: string[] = [];
  const entries = doorEntries();
  const phone = doorReachOf('ios');
  if (!same(phone.routes, entries.filter((e) => e.grant === 'phone').map((e) => e.name))) bad.push("door.json: a phone's health.door.routes is not exactly the routes door.json grants a phone");
  if (!same(phone.not_by_relay, entries.filter((e) => e.grant === 'phone' && !e.relay).map((e) => e.name))) bad.push('door.json: the routes the relay refuses a phone are not the ones door.json marks relay: false');
  // The names are what `health.door.routes` lists to a linked computer, which reaches every route.
  if (!same(entries.map((e) => e.name), doorReachOf(MACHINE_PLATFORM).routes)) bad.push("door.json: its routes are not a linked computer's health.door.routes, in order");
  for (const e of entries.filter((x) => x.window)) {
    if (doorRouteOf(e.method, sample(e.path), true) === null) bad.push(`door.json: ${e.name} (${e.path}) does not reach the door`);
    else if ((doorRouteOf(e.method, sample(e.path), false) !== null) !== (e.grant === 'phone')) bad.push(`door.json: ${e.name} is granted ${e.grant}, and a phone's token says otherwise`);
  }
  for (const e of entries) {
    if (e.method === 'GET' && (e.kind !== 'read' || e.key !== null)) bad.push(`door.json: ${e.name} is a GET, so its kind is read and it has no key`);
    else if (e.kind === 'bytes' && (e.key !== 'query' || e.relay)) bad.push(`door.json: ${e.name} takes a file: its key rides the query and the relay never carries it`);
    else if (e.method === 'POST' && e.kind !== 'bytes' && e.auth === 'token' && e.name !== 'POST revoke' && e.key !== 'body') bad.push(`door.json: ${e.name} is a write with no key in its body`);
  }
  if (entries.find((e) => e.name === 'GET events')?.relay !== false) bad.push('door.json: GET events, the stream, is carried by the relay');
  if (entries.find((e) => e.name === 'POST pair')?.auth !== 'none') bad.push('door.json: POST pair asks for a token');
  return bad;
}

/** A doc comment on a wire type changes no generated byte. */
export function schemaRules(): string[] {
  const file = 'packages/core/inbox-types.ts';
  const text = readRepoText(file);
  const at = text.search(/export (interface|type) InboxListRow\b/);
  if (at < 0) return [`schema: ${file} exports no InboxListRow, the type this rule comments; name another wire type in scripts/mobile/rules.ts`];
  const edited = `${text.slice(0, at)}/** A comment-only edit: it must change no generated byte. */\n${text.slice(at)}`.replace(/(\n  thread_id: string;)/, '\n  /** Another comment-only edit. */$1');
  return same(schemaWith({ [file]: edited }), buildSchema()) ? [] : ['schema: a doc comment on a wire type changed the generated schema (scripts/mobile/schema.ts must ignore comments)'];
}

/** Each word with a part, made by the product's own function (a word that branches on its part would differ from its template). */
const WORD_MAKERS: Record<string, (part: string) => string> = {
  'delivery.auto_after': (m) => autoAfterText(Number(m)),
  'delivery.sent_queued': (n) => sentRowLine(n, true),
  'delivery.sent_saved': (n) => sentRowLine(n, false),
  'delivery.reask_waiting': (n) => reaskRowLine(n, '2026-01-01T00:00:00.000Z', true),
  'delivery.reask_queued': (n) => reaskRowLine(n, null, true),
  'delivery.reask_saved': (n) => reaskRowLine(n, null, false),
};

/** A template filled in prints what the window prints, for every value of its part; every section has its name. */
export function wordRules(): string[] {
  const bad: string[] = [];
  const words = buildWords();
  for (const key of Object.keys(words).filter((k) => words[k]!.parts.length)) {
    const word = words[key]!;
    const make = WORD_MAKERS[key];
    if (!make) {
      bad.push(`words: ${key} has a part and no maker: add it to WORD_MAKERS in scripts/mobile/rules.ts`);
      continue;
    }
    for (const value of word.parts.includes('minutes') ? ['0', '1', '2', '17'] : ['Ada', 'Grace Hopper', 'a', '2']) {
      const filled = word.text.replace(/\{(\w+)\}/g, value);
      if (filled !== make(value)) bad.push(`words: ${key} with ${value} prints "${filled}", the window prints "${make(value)}" (one template cannot hold it; the app needs its own rule)`);
    }
  }
  for (const { id, label } of INBOX_SECTIONS) if (words[`section.${id}`]?.text !== label) bad.push(`words: section.${id} is not "${label}"`);
  return bad;
}
