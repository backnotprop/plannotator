/**
 * vectors/stream.json: stream bytes and the frames the window's own reader
 * (packages/inbox/sharedEvents.ts parseEventStreamText) takes from them.
 *
 *   bun scripts/mobile/vectors-stream.ts [--check]
 *
 * The app reads the stream in pieces as they arrive; for the same bytes cut at
 * any of the fixture's points it must give these frames. Its own generator and
 * run (all.ts and check.ts call it apart) because it imports the window's
 * reader: a window change re-checks this suite, not the rest of the contract.
 */
import { parseEventStreamText } from '../../packages/inbox/sharedEvents';
import { cli, jsonText, readRepoText, type Output } from './lib';

export const STREAM_FIXTURE = 'apps/mobile/contract/fixtures/stream.json';
export const STREAM_VECTORS = 'apps/mobile/contract/vectors/stream.json';

export function streamVectors(): unknown {
  const fixture = JSON.parse(readRepoText(STREAM_FIXTURE)) as { text: string; cuts: number[] };
  for (const cut of fixture.cuts) if (cut <= 0 || cut >= fixture.text.length) throw new Error(`vectors-stream.ts: cut ${cut} is outside the text`);
  return {
    about: `GENERATED by scripts/mobile/vectors-stream.ts from ${STREAM_FIXTURE}. Do not edit. Frames the window reads from "text"; a frame of a name the window does not know is dropped, and so is a block with no data line.`,
    text: fixture.text,
    cuts: fixture.cuts,
    frames: parseEventStreamText(fixture.text),
  };
}

export function generateStreamVectors(): Output[] {
  return [{ path: STREAM_VECTORS, text: jsonText(streamVectors()) }];
}

if (import.meta.main) await cli('vectors-stream', generateStreamVectors);
