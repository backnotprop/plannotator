/**
 * Writes apps/hook/hooks/mod/inbox-default-tools.ts: the tool list a real
 * Plannotator Inbox answers on `/mcp` `tools/list`, as the Claude Code mod
 * parses it (parseInboxToolList). The mod registers `plannotator_inbox` from
 * that list when no Inbox has run yet on this computer, so Claude Code has the
 * tool before the first run (the first call starts the Inbox).
 *
 *   bun run scripts/sync-mod-inbox-tools.ts
 *
 * Run after changing an Inbox MCP tool (packages/server/inbox-mcp.ts);
 * apps/hook/hooks/mod/inbox-default-tools.test.ts fails until you do.
 *
 * Starts an in-process Inbox in a fresh temp data dir (never the person's).
 */
import { mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const dataDir = realpathSync(mkdtempSync(join(tmpdir(), "plannotator-sync-mod-tools-")));
// The Inbox reads config.json through the env even when given dataDir.
process.env.PLANNOTATOR_DATA_DIR = dataDir;

const { startInboxServer } = await import("../packages/server/inbox");
const { mcpAnswerOf, parseInboxToolList } = await import("../packages/shared/inbox/connection");

const inbox = await startInboxServer({ dataDir, version: "sync", binaryPath: null, phones: false });
try {
  const response = await fetch(`http://127.0.0.1:${inbox.port}/mcp`, {
    method: "POST",
    headers: { "content-type": "application/json", accept: "application/json, text/event-stream" },
    body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "tools/list", params: {} }),
  });
  const answer = mcpAnswerOf(await response.text());
  const tools = parseInboxToolList(answer?.result);
  if (tools.length === 0) throw new Error("the Inbox listed no tools");
  const out = resolve(import.meta.dir, "../apps/hook/hooks/mod/inbox-default-tools.ts");
  writeFileSync(
    out,
    [
      "// GENERATED by scripts/sync-mod-inbox-tools.ts from a real Inbox's /mcp tools/list. Do not edit;",
      "// run `bun run scripts/sync-mod-inbox-tools.ts` after changing an Inbox MCP tool.",
      "//",
      "// The tools `plannotator_inbox` carries in a Claude Code session that starts before",
      "// this computer ever ran the Inbox (no inbox/inbox.json, nothing remembered): the",
      "// first call starts the Inbox with `plannotator inbox --background`.",
      "import type { InboxToolInfo } from './inbox-contract'",
      "",
      `export const INBOX_DEFAULT_TOOLS: readonly InboxToolInfo[] = ${JSON.stringify(tools, null, 2)}`,
      "",
    ].join("\n"),
  );
  process.stdout.write(`wrote ${out} (${tools.length} tools)\n`);
} finally {
  inbox.stop();
  rmSync(dataDir, { recursive: true, force: true });
}
process.exit(0);
