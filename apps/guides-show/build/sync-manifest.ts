import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { GUIDE_LANGUAGE_IDS } from '../../../packages/core/guide-format';
import type { ViewerManifest } from './manifest-plugin';

type ViewerPin = Pick<ViewerManifest, 'js' | 'css' | 'jsIntegrity' | 'cssIntegrity'> & { langs?: ViewerManifest['langs'] };

const built = path.resolve(import.meta.dirname, '../dist/viewer/manifest.json');
const fallback = path.resolve(import.meta.dirname, 'fallback-viewer-pin.json');
const target = path.resolve(import.meta.dirname, '../../../packages/core/guide-viewer-manifest.ts');

function render(pin: ViewerPin, origin: string): string {
  const langs = Object.entries(pin.langs ?? {})
    .filter(([lang]) => GUIDE_LANGUAGE_IDS.includes(lang))
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([lang, file]) => `    ${JSON.stringify(lang)}: ${JSON.stringify(file)},`)
    .join('\n');
  return `// @generated by apps/guides-show/build/sync-manifest.ts (${origin}) — DO NOT EDIT, NOT COMMITTED.
// Regenerate: bun run build:viewer-pin
// Describes the guides.show viewer build this Plannotator build pins into
// exported guides (paths relative to the viewer base URL, plus SRI hashes).
import type { GuideViewerAssets } from "./guide-format";

export const GUIDE_VIEWER_MANIFEST: Omit<GuideViewerAssets, "baseUrl"> = {
  js: ${JSON.stringify(pin.js)},
  css: ${JSON.stringify(pin.css)},
  jsIntegrity: ${JSON.stringify(pin.jsIntegrity)},
  cssIntegrity: ${JSON.stringify(pin.cssIntegrity)},
  langs: {
${langs}
  },
};
`;
}

if (process.argv.includes('--if-missing')) {
  if (existsSync(target)) process.exit(0);
  const pin = JSON.parse(readFileSync(fallback, 'utf8')) as ViewerPin;
  writeFileSync(target, render(pin, 'fallback pin'));
  console.log(`wrote the fallback viewer pin to ${target} (bun run build:viewer-pin pins this checkout's viewer)`);
} else {
  if (!existsSync(built)) {
    console.error(`${built} is missing. Run: bun run build:viewer-pin`);
    process.exit(1);
  }
  const pin = JSON.parse(readFileSync(built, 'utf8')) as ViewerManifest;
  writeFileSync(target, render(pin, 'viewer build'));
  console.log(`wrote ${target} (${pin.js}, ${pin.css})`);
}
