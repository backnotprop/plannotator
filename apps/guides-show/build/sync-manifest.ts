/**
 * Keep the checked-in viewer manifest module — what Plannotator's export path
 * embeds (`@plannotator/core/guide-viewer-manifest`) — equal to what the viewer
 * build actually produces.
 *   bun build/sync-manifest.ts          # regenerate from dist/viewer/manifest.json
 *   bun build/sync-manifest.ts --check  # exit 1 if it differs (CI / release gate)
 * The viewer build is deterministic (content hashes, no timestamps), so a
 * mismatch means the viewer changed without the manifest being refreshed —
 * regenerate, commit, and the same release both publishes the viewer and
 * ships a binary that pins it (decision record D8/D10).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { GUIDE_LANGUAGE_IDS } from '../../../packages/core/guide-format';
import type { ViewerManifest } from './manifest-plugin';

const built = path.resolve(import.meta.dirname, '../dist/viewer/manifest.json');
const target = path.resolve(import.meta.dirname, '../../../packages/core/guide-viewer-manifest.ts');
const manifest = JSON.parse(readFileSync(built, 'utf8')) as ViewerManifest;

// Every grammar chunk is built and published, but the pin only lists the ids
// `detectGuideLanguages` can produce: those are the only modulepreload hints an
// export can ever emit, and the rest would just bloat this file.
const langs = Object.entries(manifest.langs)
  .filter(([lang]) => GUIDE_LANGUAGE_IDS.includes(lang))
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([lang, file]) => `    ${JSON.stringify(lang)}: ${JSON.stringify(file)},`)
  .join('\n');

const source = `// @generated by apps/guides-show/build/sync-manifest.ts — DO NOT EDIT.
// Regenerate: bun run --cwd apps/guides-show build:viewer && bun run --cwd apps/guides-show sync:manifest
// Describes the guides.show viewer build this Plannotator version pins into
// exported guides (paths relative to the viewer base URL, plus SRI hashes).
import type { GuideViewerAssets } from "./guide-format";

export const GUIDE_VIEWER_MANIFEST: Omit<GuideViewerAssets, "baseUrl"> = {
  js: ${JSON.stringify(manifest.js)},
  css: ${JSON.stringify(manifest.css)},
  jsIntegrity: ${JSON.stringify(manifest.jsIntegrity)},
  cssIntegrity: ${JSON.stringify(manifest.cssIntegrity)},
  langs: {
${langs}
  },
};
`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(target, 'utf8'); } catch {}
  if (current !== source) {
    console.error('packages/core/guide-viewer-manifest.ts is out of date. Run: bun run --cwd apps/guides-show build:viewer && bun run --cwd apps/guides-show sync:manifest');
    process.exit(1);
  }
  console.log('guide-viewer-manifest.ts is in sync');
} else {
  writeFileSync(target, source);
  console.log(`wrote ${target}`);
}
