/**
 * A step-through: an algorithm shown one state at a time, next to its code.
 * An agent writes it by running the algorithm and saving a state at each step
 * that teaches something, and a drawn view plays it where it puts
 * `<div data-steps="id"></div>`.
 *
 *   code    the lines the reader follows (one is lit per step)
 *   show    what is drawn: "array" (bars), "graph" (nodes and edges), or
 *           "rows" (labelled rows of boxes: hash buckets, a linked list, a cache)
 *   frames  the states, in order. Each is whole: it says everything drawn at
 *           that step, so back, scrub and a reload are the same as stepping.
 *
 * Roles give the drawing its colours, the way textbooks and VisuAlgo do:
 *   look   being compared or examined     (amber)
 *   now    the one acting this step       (blue, the board's mark)
 *   moved  just written, swapped, relaxed (red)
 *   done   in its final place, settled    (green)
 *   wait   waiting: in the queue, the frontier (outlined)
 *   off    out of play this step          (faded)
 *
 * Browser-safe, no DOM.
 */
import type { ShapeCheck } from './shape';

export const SHAPE_STEPS_VERSION = 1;

export type ShapeStepRole = 'look' | 'now' | 'moved' | 'done' | 'wait' | 'off';
export const SHAPE_STEP_ROLES: readonly ShapeStepRole[] = ['look', 'now', 'moved', 'done', 'wait', 'off'];

export interface ShapeStepNode {
  id: string;
  label?: string;
  /** Where it sits, 0–100 across and down. The agent lays the graph out the way a textbook would. */
  x: number;
  y: number;
  /** Drawn as a small dot with its label beside it (a key on a hash ring, a point). */
  small?: boolean;
}

export interface ShapeStepEdge {
  from: string;
  to: string;
  /** A weight, drawn at the middle of the edge. */
  w?: number;
}

export interface ShapeStepFrame {
  /** The code line running, from 1. */
  line: number;
  /** One sentence: what this step does and why. */
  say: string;
  /** array: the values now. */
  array?: number[];
  /** array: indices by role. */
  cells?: Partial<Record<ShapeStepRole, number[]>>;
  /** array: named pointers to indices ({ "i": 3, "j": 2 }). */
  ptr?: Record<string, number>;
  /** graph: node ids by role. */
  nodes?: Partial<Record<ShapeStepRole, string[]>>;
  /** graph: edges by role, each as [from, to]. */
  edges?: Partial<Record<ShapeStepRole, [string, string][]>>;
  /** graph: a word beside each node (a distance; null draws ∞). */
  tags?: Record<string, number | string | null>;
  /** An ordered list drawn as a strip: a queue, a stack, a heap. */
  queue?: (string | number)[];
  /** rows: the rows now, top to bottom (buckets, a list, a cache). */
  rows?: ShapeStepRow[];
  /** Variables worth watching ({ "lo": 0, "hi": 7 }). */
  vars?: Record<string, number | string | boolean | null>;
}

export interface ShapeStepRow {
  /** The word at the row's start ("0", "head", "bucket 3"). */
  label: string;
  /** The boxes, left to right. */
  items: (string | number)[];
  /** The whole row's role (the bucket being looked at). */
  role?: ShapeStepRole;
  /** Each box's role, by position; null for none. */
  roles?: (ShapeStepRole | null)[];
  /** This row's own join, over the step-through's `rowsJoin` (a chained list beside a plain map). */
  join?: 'arrow' | 'none';
}

export interface ShapeSteps {
  steps: 1;
  title: string;
  /** Where it came from: "insertion sort, generated by running it on [5,2,…]". */
  source?: string;
  code: { lang?: string; lines: string[] };
  show: 'array' | 'graph' | 'rows';
  /** graph: the nodes and edges every frame draws. `ring` draws the circle the nodes sit on (a hash ring). */
  graph?: { nodes: ShapeStepNode[]; edges: ShapeStepEdge[]; directed?: boolean; ring?: boolean };
  /** rows: how boxes in a row join. "arrow": a chain (a bucket's list, a linked list). Default: side by side. */
  rowsJoin?: 'arrow' | 'none';
  /** What the strip is called ("queue", "stack", "pq"). */
  queueLabel?: string;
  frames: ShapeStepFrame[];
}

export const SHAPE_STEPS_LIMITS = { frames: 400, lines: 60, lineChars: 110, say: 180, title: 120, array: 48, nodes: 40, edges: 90, queue: 24, vars: 8, id: 24, rows: 16, rowItems: 16, cell: 14 } as const;

const ID_RE = /^[A-Za-z0-9_.:-]+$/;
const STEPS_KEYS = ['steps', 'title', 'source', 'code', 'show', 'graph', 'rowsJoin', 'queueLabel', 'frames'];
const FRAME_KEYS = ['line', 'say', 'array', 'cells', 'ptr', 'nodes', 'edges', 'tags', 'queue', 'rows', 'vars'];
const isRecord = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);
const isNum = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v);

/** Validate a step-through. Every problem names its field, the way `checkShapeBoard` does. */
export function checkShapeSteps(input: unknown, field = 'steps'): ShapeCheck<ShapeSteps> {
  const errors: string[] = [];
  const fail = (at: string, why: string) => {
    if (errors.length < 30) errors.push(`${at}: ${why}`);
  };
  if (!isRecord(input)) return { ok: false, errors: [`${field}: must be an object { steps: 1, title, code, show, frames }`] };
  if (input.steps !== 1) fail(`${field}.steps`, 'must be 1 (the format version)');
  for (const key of Object.keys(input)) if (!STEPS_KEYS.includes(key)) fail(`${field}.${key}`, `is not part of a step-through (${STEPS_KEYS.join(', ')})`);
  const text = (v: unknown, at: string, max: number, required: boolean): string | undefined => {
    if (v === undefined || v === null) {
      if (required) fail(at, 'is required');
      return undefined;
    }
    if (typeof v !== 'string') return fail(at, 'must be text'), undefined;
    const t = v.trim();
    if (required && !t) fail(at, 'is empty');
    if (t.length > max) fail(at, `is ${t.length} characters; at most ${max}`);
    return t || undefined;
  };
  const title = text(input.title, `${field}.title`, SHAPE_STEPS_LIMITS.title, true);
  const source = text(input.source, `${field}.source`, 200, false);
  const queueLabel = text(input.queueLabel, `${field}.queueLabel`, 20, false);

  // The code.
  let lines: string[] = [];
  let lang: string | undefined;
  if (!isRecord(input.code) || !Array.isArray(input.code.lines)) fail(`${field}.code`, 'must be { lang?, lines: ["…", …] }');
  else {
    lang = text(input.code.lang, `${field}.code.lang`, 20, false);
    if (!input.code.lines.length) fail(`${field}.code.lines`, 'is empty');
    if (input.code.lines.length > SHAPE_STEPS_LIMITS.lines) fail(`${field}.code.lines`, `has ${input.code.lines.length} lines; at most ${SHAPE_STEPS_LIMITS.lines}: show the function, not the file`);
    lines = input.code.lines.slice(0, SHAPE_STEPS_LIMITS.lines).map((l, i) => {
      if (typeof l !== 'string') return fail(`${field}.code.lines[${i}]`, 'must be text'), '';
      if (l.length > SHAPE_STEPS_LIMITS.lineChars) fail(`${field}.code.lines[${i}]`, `is ${l.length} characters; at most ${SHAPE_STEPS_LIMITS.lineChars}`);
      return l.replace(/\t/g, '    ').replace(/\s+$/, '');
    });
  }

  const show = input.show;
  if (show !== 'array' && show !== 'graph' && show !== 'rows') fail(`${field}.show`, 'must be "array", "graph" or "rows"');
  let rowsJoin: ShapeSteps['rowsJoin'];
  if (input.rowsJoin !== undefined) {
    if (show !== 'rows') fail(`${field}.rowsJoin`, 'is only for rows');
    else if (input.rowsJoin === 'arrow' || input.rowsJoin === 'none') rowsJoin = input.rowsJoin;
    else fail(`${field}.rowsJoin`, 'must be "arrow" or "none"');
  }
  // The graph.
  let graph: ShapeSteps['graph'];
  const nodeIds = new Set<string>();
  const edgeKeys = new Set<string>();
  if (show === 'graph') {
    const g = input.graph;
    if (!isRecord(g) || !Array.isArray(g.nodes) || !Array.isArray(g.edges)) fail(`${field}.graph`, 'must be { nodes: [{ id, x, y }], edges: [{ from, to, w? }] }');
    else {
      const directed = g.directed === true;
      if (g.nodes.length > SHAPE_STEPS_LIMITS.nodes) fail(`${field}.graph.nodes`, `has ${g.nodes.length}; at most ${SHAPE_STEPS_LIMITS.nodes}`);
      if (g.edges.length > SHAPE_STEPS_LIMITS.edges) fail(`${field}.graph.edges`, `has ${g.edges.length}; at most ${SHAPE_STEPS_LIMITS.edges}`);
      const nodes: ShapeStepNode[] = [];
      g.nodes.slice(0, SHAPE_STEPS_LIMITS.nodes).forEach((n, i) => {
        const at = `${field}.graph.nodes[${i}]`;
        if (!isRecord(n)) return fail(at, 'must be { id, x, y }');
        const id = typeof n.id === 'string' ? n.id.trim() : '';
        if (!id || id.length > SHAPE_STEPS_LIMITS.id || !ID_RE.test(id)) return fail(`${at}.id`, `must be a short id (letters, digits, _ . : -; at most ${SHAPE_STEPS_LIMITS.id})`);
        if (nodeIds.has(id)) return fail(`${at}.id`, `"${id}" is used twice`);
        if (!isNum(n.x) || n.x < 0 || n.x > 100) fail(`${at}.x`, 'must be a number from 0 to 100');
        if (!isNum(n.y) || n.y < 0 || n.y > 100) fail(`${at}.y`, 'must be a number from 0 to 100');
        nodeIds.add(id);
        const label = text(n.label, `${at}.label`, 12, false);
        nodes.push({ id, ...(label ? { label } : {}), x: isNum(n.x) ? n.x : 0, y: isNum(n.y) ? n.y : 0, ...(n.small === true ? { small: true } : {}) });
      });
      const edges: ShapeStepEdge[] = [];
      g.edges.slice(0, SHAPE_STEPS_LIMITS.edges).forEach((e, i) => {
        const at = `${field}.graph.edges[${i}]`;
        if (!isRecord(e)) return fail(at, 'must be { from, to, w? }');
        const ok = (v: unknown, k: string) => (typeof v === 'string' && nodeIds.has(v) ? true : (fail(`${at}.${k}`, `must be a node id (${[...nodeIds].slice(0, 4).join(', ')}${nodeIds.size > 4 ? ', …' : ''})`), false));
        if (!ok(e.from, 'from') || !ok(e.to, 'to')) return;
        if (e.w !== undefined && !isNum(e.w)) fail(`${at}.w`, 'must be a number');
        edgeKeys.add(`${e.from}>${e.to}`);
        if (!directed) edgeKeys.add(`${e.to}>${e.from}`);
        edges.push({ from: e.from as string, to: e.to as string, ...(isNum(e.w) ? { w: e.w } : {}) });
      });
      graph = { nodes, edges, ...(directed ? { directed } : {}), ...(g.ring === true ? { ring: true } : {}) };
    }
  }

  // The frames.
  const frames: ShapeStepFrame[] = [];
  if (!Array.isArray(input.frames) || !input.frames.length) fail(`${field}.frames`, 'must be a list of states, at least one');
  else {
    if (input.frames.length > SHAPE_STEPS_LIMITS.frames) fail(`${field}.frames`, `has ${input.frames.length}; at most ${SHAPE_STEPS_LIMITS.frames}: keep the steps that teach`);
    input.frames.slice(0, SHAPE_STEPS_LIMITS.frames).forEach((f, i) => {
      const at = `${field}.frames[${i}]`;
      if (!isRecord(f)) return fail(at, 'must be { line, say, … }');
      for (const key of Object.keys(f)) if (!FRAME_KEYS.includes(key)) fail(`${at}.${key}`, `is not part of a frame (${FRAME_KEYS.join(', ')})`);
      if (!Number.isInteger(f.line) || (f.line as number) < 1 || (f.line as number) > Math.max(1, lines.length)) fail(`${at}.line`, `must be a code line from 1 to ${lines.length}`);
      const say = text(f.say, `${at}.say`, SHAPE_STEPS_LIMITS.say, true) ?? '';
      const out: ShapeStepFrame = { line: Number.isInteger(f.line) ? (f.line as number) : 1, say };
      const roles = <T,>(v: unknown, k: string, item: (x: unknown, at: string) => T | undefined): Partial<Record<ShapeStepRole, T[]>> | undefined => {
        if (v === undefined) return undefined;
        if (!isRecord(v)) return fail(`${at}.${k}`, `must be { ${SHAPE_STEP_ROLES.join(', ')} }: lists by role`), undefined;
        const r: Partial<Record<ShapeStepRole, T[]>> = {};
        for (const [role, list] of Object.entries(v)) {
          if (!SHAPE_STEP_ROLES.includes(role as ShapeStepRole)) {
            fail(`${at}.${k}.${role}`, `is not a role; use ${SHAPE_STEP_ROLES.join(', ')}`);
            continue;
          }
          if (!Array.isArray(list)) {
            fail(`${at}.${k}.${role}`, 'must be a list');
            continue;
          }
          const items: T[] = [];
          list.forEach((x, j) => {
            const got = item(x, `${at}.${k}.${role}[${j}]`);
            if (got !== undefined) items.push(got);
          });
          r[role as ShapeStepRole] = items;
        }
        return r;
      };
      if (show === 'array') {
        if (!Array.isArray(f.array) || !f.array.length || !f.array.every(isNum)) fail(`${at}.array`, 'must be the array of numbers at this step');
        else if (f.array.length > SHAPE_STEPS_LIMITS.array) fail(`${at}.array`, `has ${f.array.length} values; at most ${SHAPE_STEPS_LIMITS.array}`);
        else {
          const n = f.array.length;
          out.array = f.array as number[];
          const index = (x: unknown, a: string) => (Number.isInteger(x) && (x as number) >= 0 && (x as number) < n ? (x as number) : (fail(a, `must be an index from 0 to ${n - 1}`), undefined));
          const cells = roles(f.cells, 'cells', index);
          if (cells) out.cells = cells;
          if (f.ptr !== undefined) {
            if (!isRecord(f.ptr)) fail(`${at}.ptr`, 'must be { "i": 3, … }');
            else {
              out.ptr = {};
              for (const [name, v] of Object.entries(f.ptr)) {
                if (name.length > 8) fail(`${at}.ptr.${name}`, 'a pointer name is at most 8 characters');
                // A pointer may sit one past either end (j = -1 when insertion sort runs off the front).
                else if (!Number.isInteger(v) || (v as number) < -1 || (v as number) > n) fail(`${at}.ptr.${name}`, `must be an index from -1 to ${n}`);
                else out.ptr[name] = v as number;
              }
            }
          }
        }
      } else if (show === 'graph') {
        const node = (x: unknown, a: string) => (typeof x === 'string' && nodeIds.has(x) ? x : (fail(a, `"${String(x)}" is not a node id`), undefined));
        const edge = (x: unknown, a: string): [string, string] | undefined =>
          Array.isArray(x) && x.length === 2 && edgeKeys.has(`${x[0]}>${x[1]}`) ? [x[0] as string, x[1] as string] : (fail(a, `${JSON.stringify(x)} is not an edge of the graph`), undefined);
        const nodes = roles(f.nodes, 'nodes', node);
        if (nodes) out.nodes = nodes;
        const edges = roles(f.edges, 'edges', edge);
        if (edges) out.edges = edges;
        if (f.tags !== undefined) {
          if (!isRecord(f.tags)) fail(`${at}.tags`, 'must be { nodeId: value }');
          else {
            out.tags = {};
            for (const [id, v] of Object.entries(f.tags)) {
              if (!nodeIds.has(id)) fail(`${at}.tags.${id}`, 'is not a node id');
              else if (v !== null && !isNum(v) && !(typeof v === 'string' && v.length <= 10)) fail(`${at}.tags.${id}`, 'must be a number, null (∞) or a short word');
              else out.tags[id] = v as number | string | null;
            }
          }
        }
      } else if (show === 'rows') {
        const rows = f.rows;
        const role = (x: unknown, a: string) => (x === null || x === undefined ? null : SHAPE_STEP_ROLES.includes(x as ShapeStepRole) ? (x as ShapeStepRole) : (fail(a, `is not a role; use ${SHAPE_STEP_ROLES.join(', ')} or null`), null));
        if (!Array.isArray(rows)) fail(`${at}.rows`, 'must be the rows at this step: [{ label, items, role?, roles? }]');
        else if (rows.length > SHAPE_STEPS_LIMITS.rows) fail(`${at}.rows`, `has ${rows.length}; at most ${SHAPE_STEPS_LIMITS.rows}`);
        else {
          out.rows = [];
          rows.forEach((r, j) => {
            const ra = `${at}.rows[${j}]`;
            if (!isRecord(r) || !Array.isArray(r.items)) return fail(ra, 'must be { label, items: [ … ], role?, roles? }');
            const label = typeof r.label === 'string' || isNum(r.label) ? String(r.label) : (fail(`${ra}.label`, 'must be a short word'), '');
            if (label.length > SHAPE_STEPS_LIMITS.cell) fail(`${ra}.label`, `is ${label.length} characters; at most ${SHAPE_STEPS_LIMITS.cell}`);
            if (r.items.length > SHAPE_STEPS_LIMITS.rowItems) return fail(`${ra}.items`, `has ${r.items.length}; at most ${SHAPE_STEPS_LIMITS.rowItems}`);
            const items: (string | number)[] = [];
            r.items.forEach((x, k) => {
              if (isNum(x)) items.push(x);
              else if (typeof x === 'string' && x.length <= SHAPE_STEPS_LIMITS.cell) items.push(x);
              else fail(`${ra}.items[${k}]`, `must be a number or a word of at most ${SHAPE_STEPS_LIMITS.cell} characters`);
            });
            const row: ShapeStepRow = { label, items };
            if (r.join !== undefined) {
              if (r.join === 'arrow' || r.join === 'none') row.join = r.join;
              else fail(`${ra}.join`, 'must be "arrow" or "none"');
            }
            if (r.role !== undefined && r.role !== null) {
              const got = role(r.role, `${ra}.role`);
              if (got) row.role = got;
            }
            if (r.roles !== undefined) {
              if (!Array.isArray(r.roles) || r.roles.length > items.length) fail(`${ra}.roles`, `must be a list of roles (or null), one per box, at most ${items.length}`);
              else row.roles = r.roles.map((x, k) => role(x, `${ra}.roles[${k}]`));
            }
            out.rows!.push(row);
          });
        }
      }
      if (f.queue !== undefined) {
        if (!Array.isArray(f.queue) || f.queue.length > SHAPE_STEPS_LIMITS.queue || !f.queue.every((q) => isNum(q) || (typeof q === 'string' && q.length <= 20)))
          fail(`${at}.queue`, `must be at most ${SHAPE_STEPS_LIMITS.queue} numbers or short words`);
        else out.queue = f.queue as (string | number)[];
      }
      if (f.vars !== undefined) {
        if (!isRecord(f.vars) || Object.keys(f.vars).length > SHAPE_STEPS_LIMITS.vars) fail(`${at}.vars`, `must be { name: value }, at most ${SHAPE_STEPS_LIMITS.vars}`);
        else {
          out.vars = {};
          for (const [k, v] of Object.entries(f.vars)) {
            if (k.length > 16) fail(`${at}.vars.${k}`, 'a name is at most 16 characters');
            else if (v !== null && !isNum(v) && typeof v !== 'boolean' && !(typeof v === 'string' && v.length <= 24)) fail(`${at}.vars.${k}`, 'must be a number, a boolean, null or a short word');
            else out.vars[k] = v as number | string | boolean | null;
          }
        }
      }
      frames.push(out);
    });
  }

  if (errors.length || !title) return { ok: false, errors: errors.length ? errors : [`${field}.title: is required`] };
  return {
    ok: true,
    value: {
      steps: 1,
      title,
      ...(source ? { source } : {}),
      code: { ...(lang ? { lang } : {}), lines },
      show: show as ShapeSteps['show'],
      ...(graph ? { graph } : {}),
      ...(queueLabel ? { queueLabel } : {}),
      ...(rowsJoin ? { rowsJoin } : {}),
      frames,
    },
  };
}

/** The step-through ids a drawn view's HTML plays (`data-steps="id"`). No DOM. */
export function shapeHtmlSteps(html: string): string[] {
  const out: string[] = [];
  for (const m of html.matchAll(/\sdata-steps\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/gi)) out.push((m[1] ?? m[2] ?? m[3] ?? '').trim());
  return out;
}
