/**
 * Code review's package changes card in the Inbox (review parity B5): the rows under a package.json or a lockfile, for
 * the PR page (`pullPackageChanges`, over `InboxPulls.fileBytes`) and for a guided review (`guidePackageChanges`, over
 * the blobs its patch names), both through the shared service. Real git in a temp folder; a scripted pulls. No Inbox
 * is started and no real CLI, forge or registry runs.
 *
 * What regresses:
 *  - a request that names no diff (no snapshot, another message's, a base) reading the diff or a file at all;
 *  - a stale head answered with another head's rows;
 *  - the card switch (config.json `packageChanges.card` off) not holding;
 *  - a name offered to npm (the Inbox has no lookup);
 *  - a guide's sides read from anything other than the blobs its patch names, or a lockfile's unchanged manifest read
 *    from the working tree.
 */
import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { FileBytesRead } from "@plannotator/shared/review-core";
import type { InboxPulls } from "./inbox-pulls";
import { guidePackageChanges, packageCardOn, pullPackageChanges } from "./inbox-package-changes";

const manifest = (dependencies: Record<string, string>) => `${JSON.stringify({ name: "billing-svc", version: "1.0.0", dependencies }, null, 2)}\n`;
const yarnLock = (entries: Record<string, string>) =>
  `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n${Object.entries(entries)
    .map(([spec, version]) => `${spec}:\n  version "${version}"\n  resolved "https://registry.yarnpkg.com/${spec.split("@")[0]}/-/${spec.split("@")[0]}-${version}.tgz"\n`)
    .join("\n")}`;

const BEFORE = { pkg: manifest({ "left-pad": "^1.1.0" }), lock: yarnLock({ "left-pad@^1.1.0": "1.1.3" }) };
const AFTER = { pkg: manifest({ "left-pad": "^1.3.0", "tiny-queue": "^0.2.1" }), lock: yarnLock({ "left-pad@^1.3.0": "1.3.0", "tiny-queue@^0.2.1": "0.2.1" }) };

const savedDataDir = process.env.PLANNOTATOR_DATA_DIR;
let scratch = "";
let repo = "";
/** The change to package.json and its yarn.lock. */
let patch = "";
/** A lockfile-only change (package.json left alone). */
let lockOnly = "";

function git(...args: string[]): string {
  const run = Bun.spawnSync(["git", "-c", "user.name=Ada Novak", "-c", "user.email=ada@example.com", "-c", "commit.gpgsign=false", ...args], { cwd: repo, env: { ...process.env, GIT_CONFIG_NOSYSTEM: "1" } });
  if (run.exitCode !== 0) throw new Error(`git ${args.join(" ")}: ${run.stderr.toString()}`);
  return run.stdout.toString();
}

beforeAll(() => {
  scratch = realpathSync(mkdtempSync(join(tmpdir(), "inbox-package-changes-")));
  process.env.PLANNOTATOR_DATA_DIR = join(scratch, "data");
  repo = join(scratch, "repo");
  mkdirSync(repo, { recursive: true });
  git("init", "-q", "-b", "main");
  writeFileSync(join(repo, "package.json"), BEFORE.pkg);
  writeFileSync(join(repo, "yarn.lock"), BEFORE.lock);
  git("add", "-A");
  git("commit", "-q", "-m", "base");
  writeFileSync(join(repo, "package.json"), AFTER.pkg);
  writeFileSync(join(repo, "yarn.lock"), AFTER.lock);
  git("add", "-A");
  git("commit", "-q", "-m", "deps");
  patch = git("diff", "--full-index", "HEAD~1", "HEAD");
  writeFileSync(join(repo, "yarn.lock"), yarnLock({ "left-pad@^1.3.0": "1.3.0", "tiny-queue@^0.2.1": "0.2.3" }));
  git("add", "-A");
  git("commit", "-q", "-m", "a lockfile bump");
  lockOnly = git("diff", "--full-index", "HEAD~1", "HEAD");
});

afterAll(() => {
  if (savedDataDir === undefined) delete process.env.PLANNOTATOR_DATA_DIR;
  else process.env.PLANNOTATOR_DATA_DIR = savedDataDir;
  rmSync(scratch, { recursive: true, force: true });
});

interface Card { path: string; role: string; error?: unknown; changes: { name: string; kind: string; beforeVersion: string | null; afterVersion: string | null }[]; lookup: { names: string[] } }
const cardsOf = (body: unknown) => (body as { cards: Card[] }).cards;
const rowsOf = (card: Card | undefined) => Object.fromEntries((card?.changes ?? []).map((c) => [c.name, [c.kind, c.beforeVersion, c.afterVersion]]));

describe("a pull request's package changes", () => {
  const HEAD = "a".repeat(40);
  const KEY = "github.com/northwind/billing-svc#412";
  const texts: Record<string, string> = { "old package.json": BEFORE.pkg, "new package.json": AFTER.pkg, "old yarn.lock": BEFORE.lock, "new yarn.lock": AFTER.lock };
  const fake = (answerHead: string | null = HEAD) => {
    const calls = { diff: 0, reads: [] as { side: string; path: string; head: string | undefined }[] };
    const pulls: Pick<InboxPulls, "diff" | "fileBytes"> = {
      diff: async () => {
        calls.diff++;
        return { patch, partial: false, head_sha: answerHead };
      },
      fileBytes: async (_key, _scope, side, path, _oldPath, _roots, _max, _from, head): Promise<FileBytesRead> => {
        calls.reads.push({ side, path, head });
        const text = texts[`${side} ${path}`];
        return text === undefined ? { kind: "missing" } : { kind: "ok", bytes: new TextEncoder().encode(text) };
      },
    };
    return { pulls, calls };
  };
  const read = (pulls: Pick<InboxPulls, "diff" | "fileBytes">, params: Record<string, string>, cardOn = true) =>
    pullPackageChanges({ pulls, key: KEY, scope: "layer", params: new URLSearchParams(params), roots: async () => [repo], cardOn });

  test("the rows of the diff at the head on screen, each side read there; no name offered to npm", async () => {
    const { pulls, calls } = fake();
    const answer = await read(pulls, { snapshot: HEAD });
    expect(answer.status).toBe(200);
    const [card] = cardsOf(answer.body);
    expect(card?.path).toBe("package.json");
    expect(rowsOf(card)).toEqual({ "left-pad": ["upgraded", "1.1.3", "1.3.0"], "tiny-queue": ["added", null, "0.2.1"] });
    expect(card?.lookup.names).toEqual([]);
    expect((answer.body as { lookup: { total: number } }).lookup.total).toBe(0);
    expect(calls.reads.length).toBeGreaterThan(0);
    expect(calls.reads.every((r) => r.head === HEAD)).toBe(true);
  });

  test("no snapshot, a snapshot that is no commit, or a base: refused before the diff is read", async () => {
    for (const params of [{}, { snapshot: "inbox:pull:x" }, { snapshot: HEAD, base: "main" }]) {
      const { pulls, calls } = fake();
      expect((await read(pulls, params)).status).toBe(400);
      expect(calls).toEqual({ diff: 0, reads: [] });
    }
  });

  test("a head that moved on is stale: 409, no file read", async () => {
    const { pulls, calls } = fake("b".repeat(40));
    expect((await read(pulls, { snapshot: HEAD })).status).toBe(409);
    expect(calls.reads).toEqual([]);
  });

  test("the card switch off: no cards, nothing read", async () => {
    const { pulls, calls } = fake();
    const answer = await read(pulls, { snapshot: HEAD }, false);
    expect([answer.status, cardsOf(answer.body)]).toEqual([200, []]);
    expect(calls).toEqual({ diff: 0, reads: [] });
    expect(packageCardOn({ packageChanges: { card: false } })).toBe(false);
    expect(packageCardOn({})).toBe(true);
  });
});

describe("a guided review's package changes", () => {
  const MESSAGE = "msg_1";
  const read = (options: { patch?: string | null; snapshot?: string; root?: string | null; revision?: string; forge?: Parameters<typeof guidePackageChanges>[0]["forge"] } = {}) =>
    guidePackageChanges({
      patch: options.patch === undefined ? patch : options.patch,
      messageId: MESSAGE,
      root: options.root === undefined ? repo : options.root,
      ...(options.revision ? { revision: options.revision } : {}),
      params: new URLSearchParams({ snapshot: options.snapshot ?? MESSAGE }),
      ...(options.forge ? { forge: options.forge } : {}),
      cardOn: true,
    });

  test("the rows from the blobs the patch names, whatever the working tree holds now", async () => {
    writeFileSync(join(repo, "package.json"), manifest({ "left-pad": "^2.0.0" }));
    try {
      const answer = await read();
      expect(answer.status).toBe(200);
      expect(rowsOf(cardsOf(answer.body)[0])).toEqual({ "left-pad": ["upgraded", "1.1.3", "1.3.0"], "tiny-queue": ["added", null, "0.2.1"] });
    } finally {
      writeFileSync(join(repo, "package.json"), AFTER.pkg);
    }
  });

  test("a lockfile-only change: its card on the lockfile, the manifest beside it read at the commit, never the working tree", async () => {
    writeFileSync(join(repo, "package.json"), "{ not json");
    try {
      const answer = await read({ patch: lockOnly });
      const [card] = cardsOf(answer.body);
      expect(card).toMatchObject({ path: "yarn.lock", role: "lockfile" });
      expect(card?.error).toBeUndefined();
      expect(rowsOf(card)["tiny-queue"]).toEqual(["upgraded", "0.2.1", "0.2.3"]);
    } finally {
      writeFileSync(join(repo, "package.json"), AFTER.pkg);
    }
  });

  test("a lockfile-only change of a guide that pins its commit: the manifest beside it read there, not at the project's HEAD now", async () => {
    const pinned = git("rev-parse", "HEAD").trim();
    writeFileSync(join(repo, "package.json"), "{ not json");
    git("commit", "-q", "-m", "a broken manifest", "--", "package.json");
    try {
      const [card] = cardsOf((await read({ patch: lockOnly, revision: pinned })).body);
      expect(card?.error).toBeUndefined();
      expect(rowsOf(card)["tiny-queue"]).toEqual(["upgraded", "0.2.1", "0.2.3"]);
      // A guide that records none: the project's HEAD, broken manifest and all.
      expect(cardsOf((await read({ patch: lockOnly })).body)[0]?.error).toBeDefined();
    } finally {
      writeFileSync(join(repo, "package.json"), AFTER.pkg);
      git("commit", "-q", "-m", "the manifest back", "--", "package.json");
    }
  });

  test("another message's snapshot, none or a base: refused, nothing read", async () => {
    const asked: string[] = [];
    const forge = async (_side: "old" | "new", path: string): Promise<FileBytesRead> => {
      asked.push(path);
      return { kind: "missing" };
    };
    expect((await read({ snapshot: "msg_2", root: null, forge })).status).toBe(400);
    expect((await guidePackageChanges({ patch, messageId: MESSAGE, root: null, params: new URLSearchParams({ snapshot: MESSAGE, base: "main" }), forge, cardOn: true })).status).toBe(400);
    expect(asked).toEqual([]);
  });

  test("a path out of the repository is never read; a guide whose diff is gone answers 404", async () => {
    const asked: string[] = [];
    const forge = async (_side: "old" | "new", path: string): Promise<FileBytesRead> => {
      asked.push(path);
      return { kind: "ok", bytes: new TextEncoder().encode(AFTER.pkg) };
    };
    const outside = `diff --git a/../package.json b/../package.json\nnew file mode 100644\nindex 0000000..1111111\n--- /dev/null\n+++ b/../package.json\n@@ -0,0 +1 @@\n+{}\n`;
    const answer = await read({ patch: outside, root: null, forge });
    expect(answer.status).toBe(200);
    expect(asked).toEqual([]);
    expect((await read({ patch: null })).status).toBe(404);
  });

  test("a guide of a PR whose blobs are not here: the forge's side only while it is the patch's blob", async () => {
    let answer = AFTER.pkg;
    const forge = async (side: "old" | "new"): Promise<FileBytesRead> => ({ kind: "ok", bytes: new TextEncoder().encode(side === "old" ? BEFORE.pkg : answer) });
    const onlyManifest = patch.slice(0, patch.indexOf("diff --git a/yarn.lock"));
    const far = await read({ patch: onlyManifest, root: null, forge });
    expect(rowsOf(cardsOf(far.body)[0])["tiny-queue"]).toEqual(["added", null, "0.2.1"]);
    answer = manifest({ "left-pad": "^9.0.0" });
    const moved = await read({ patch: onlyManifest, root: null, forge });
    expect(cardsOf(moved.body)[0]?.error).toMatchObject({ side: "new" });
  });

  test("a package moved as a pure rename: both sides read at the guide's commit, no unreadable card", async () => {
    mkdirSync(join(repo, "packages/a"), { recursive: true });
    writeFileSync(join(repo, "packages/a/package.json"), AFTER.pkg);
    git("add", "-A");
    git("commit", "-q", "-m", "a package");
    git("mv", "packages/a", "packages/b");
    git("commit", "-q", "-m", "move the package");
    const moved = git("diff", "-M", "HEAD~1", "HEAD");
    expect(moved).toContain("similarity index 100%");
    expect(moved).not.toMatch(/^index /m);
    const answer = await read({ patch: moved, revision: git("rev-parse", "HEAD").trim() });
    expect(answer.status).toBe(200);
    expect(cardsOf(answer.body).filter((card) => card.error !== undefined)).toEqual([]);
  });
});
