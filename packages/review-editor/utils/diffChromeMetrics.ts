export const REVIEW_HEADER_HEIGHT = 40;
export const COMPACT_REVIEW_HEADER_HEIGHT = 52;
export const FILE_HEADER_HEIGHT = 32;
export const COMPACT_FILE_HEADER_HEIGHT = 44;
export const HUNK_SEPARATOR_HEIGHT = 20;
export const COMPACT_HUNK_SEPARATOR_HEIGHT = 24;

export function firstCodeLineOffset(compact: boolean): number {
  return compact
    ? COMPACT_REVIEW_HEADER_HEIGHT + COMPACT_FILE_HEADER_HEIGHT + COMPACT_HUNK_SEPARATOR_HEIGHT
    : REVIEW_HEADER_HEIGHT + FILE_HEADER_HEIGHT + HUNK_SEPARATOR_HEIGHT;
}
