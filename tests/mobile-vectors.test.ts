/**
 * The native app's contract (apps/mobile/contract, docs/agent-guides/mobile.md)
 * is what the product's code makes of itself today. Every generator runs with
 * its check: a change to the door, the wire types, the window's error codes or
 * a generator that leaves a committed contract file behind fails here, with the
 * command that brings it up to date.
 *
 * What can regress, and the test that says so:
 *  - a door route, write kind or wire type changed without regenerating
 *    door.json, the schema or Wire.swift ("is up to date");
 *  - a doc comment on a wire type churning the contract: a comment-only edit
 *    must change no generated byte ("a doc comment changes nothing");
 *  - the schema missing a file it reads from its literal list, so the picker
 *    would not select this test for it ("the schema names what it reads");
 *  - the check passing a stale or missing file ("the check finds");
 *  - the route table losing a door route, or a phone reaching a linked
 *    computer's route ("door.json is the door");
 *  - a color drawn other than the CSS says ("colors");
 *  - a word template that no longer prints what the window prints, or a word
 *    function that branches on its part, so one template cannot hold it ("words").
 */
import { describe, expect, test } from 'bun:test';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { MACHINE_PLATFORM, doorReachOf, doorRouteOf } from '../packages/server/inbox-devices';
import { DOOR_CONTRACT } from '../packages/server/inbox-door-version';
import { doorEntries, generateDoor } from '../scripts/mobile/door';
import { GENERATORS } from '../scripts/mobile/generators';
import { OUT, REGENERATE, VERSION_FILE, emit, readRepoText, type Output } from '../scripts/mobile/lib';
import { SCHEMA_SOURCES, buildSchema, schemaWith } from '../scripts/mobile/schema';

import { displayP3, linearSrgb, srgbHex } from '../scripts/mobile/tokens';
import { buildWords } from '../scripts/mobile/words';
import { autoAfterText, reaskRowLine, sentRowLine } from '../packages/core/inbox-delivery-line';
import { INBOX_SECTIONS } from '../packages/core/inbox-types';
const sample = (path: string) => path.replace(/\{path\}/g, 'a/b.png').replace(/\{card\}/g, 'crd_x').replace(/\{combine\}/g, 'cmb_x').replace(/\{action\}/g, 'a-0123abcd').replace(/\{\w+\}/g, 'x_1');

describe('the contract is up to date', () => {
  for (const [name, generate] of GENERATORS) {
    test(`${name} is up to date (else: ${REGENERATE})`, async () => {
      expect(emit(await generate(), true)).toEqual([]);
    }, 10_000);
  }

  test('a doc comment changes nothing', () => {
    const file = 'packages/core/inbox-types.ts';
    const text = readRepoText(file);
    const at = text.indexOf('export interface InboxListRow ');
    expect(at).toBeGreaterThan(0);
    const edited = `${text.slice(0, at)}/** A comment-only edit: it must change no generated byte. */\n${text.slice(at)}`.replace(
      /(\n  thread_id: string;)/,
      '\n  /** Another comment-only edit. */$1',
    );
    expect(edited).not.toBe(text);
    expect(schemaWith({ [file]: edited })).toEqual(buildSchema());
  }, 10_000);

  test('the schema names what it reads', () => {
    const schema = buildSchema() as { $defs: Record<string, { 'x-source'?: string }> };
    const sources = new Set(Object.values(schema.$defs).map((d) => d['x-source']).filter((s): s is string => !!s));
    for (const s of sources) expect(SCHEMA_SOURCES as readonly string[], s).toContain(s);
  });

  test('the check finds a stale or a missing file', () => {
    const dir = mkdtempSync(join(tmpdir(), 'mobile-contract-'));
    const outputs: Output[] = [{ path: 'a/x.json', text: '{}\n' }];
    expect(emit(outputs, true, dir), 'missing').toEqual(['a/x.json']);
    emit(outputs, false, dir);
    expect(emit(outputs, true, dir), 'written').toEqual([]);
    expect(emit([{ path: 'a/x.json', text: '{ }\n' }], true, dir), 'changed').toEqual(['a/x.json']);
  });
});

describe('door.json is the door', () => {
  const entries = doorEntries();

  test('VERSION is the door\'s contract number, and Wire.swift and the decode baseline carry the same', () => {
    expect(readRepoText(VERSION_FILE)).toBe(`${DOOR_CONTRACT}\n`);
    expect(readRepoText(OUT.swift)).toContain(`public let wireContract = ${DOOR_CONTRACT}\n`);
    expect((JSON.parse(readRepoText(OUT.required)) as { contract: number }).contract).toBe(DOOR_CONTRACT);
  });

  test('a phone\'s health lists exactly the phone routes, and the relay refuses exactly those door.json marks', () => {
    const phone = doorReachOf('ios');
    expect(phone.routes).toEqual(entries.filter((e) => e.grant === 'phone').map((e) => e.name));
    expect(phone.not_by_relay).toEqual(entries.filter((e) => e.grant === 'phone' && !e.relay).map((e) => e.name));
  });

  test('every route the door lists is there, by the name health gives it, and reaches the door', () => {
    // The names are what `health.door.routes` lists to a linked computer, which reaches every route.
    expect(entries.map((e) => e.name)).toEqual(doorReachOf(MACHINE_PLATFORM).routes);
    for (const e of entries.filter((x) => x.window)) {
      const asMachine = doorRouteOf(e.method, sample(e.path), true);
      expect(asMachine, e.name).not.toBeNull();
      expect(doorRouteOf(e.method, sample(e.path), false) !== null, `${e.name} grant`).toBe(e.grant === 'phone');
    }
  });

  test('a write has its key and its kind; a raw upload is never relayed', () => {
    for (const e of entries) {
      if (e.method === 'GET') expect([e.kind, e.key], e.name).toEqual(['read', null]);
      else if (e.kind === 'bytes') expect([e.key, e.relay], e.name).toEqual(['query', false]);
      else if (e.auth === 'token' && e.name !== 'POST revoke') expect(e.key, e.name).toBe('body');
    }
    expect(entries.find((e) => e.name === 'GET events')!.relay).toBe(false);
    expect(entries.find((e) => e.name === 'POST pair')!.auth).toBe('none');
  });
});

describe('colors', () => {
  test('oklch and hex convert to the sRGB and Display P3 a browser draws', () => {
    // CSS Color 4's own reference points: sRGB red, green and blue, and white.
    expect(srgbHex(linearSrgb('oklch(0.62796 0.25768 29.234)')!)).toBe('#ff0000');
    expect(srgbHex(linearSrgb('oklch(0.86644 0.29483 142.495)')!)).toBe('#00ff00');
    expect(srgbHex(linearSrgb('oklch(0.45201 0.31321 264.052)')!)).toBe('#0000ff');
    expect(displayP3(linearSrgb('oklch(1 0 0)')!)).toEqual([1, 1, 1]);
    expect(displayP3(linearSrgb('#ff0000')!)).toEqual([0.9175, 0.2003, 0.1386]);
    expect(srgbHex(linearSrgb('#336699')!)).toBe('#336699');
    expect(linearSrgb('0.625rem')).toBeNull();
  });
});

/** Each word with a part, made by the product's own function (a word that branches on its part would differ from its template). */
const WORD_MAKERS: Record<string, (part: string) => string> = {
  'delivery.auto_after': (m) => autoAfterText(Number(m)),
  'delivery.sent_queued': (n) => sentRowLine(n, true),
  'delivery.sent_saved': (n) => sentRowLine(n, false),
  'delivery.reask_waiting': (n) => reaskRowLine(n, '2026-01-01T00:00:00.000Z', true),
  'delivery.reask_queued': (n) => reaskRowLine(n, null, true),
  'delivery.reask_saved': (n) => reaskRowLine(n, null, false),
};

describe('words', () => {
  const words = buildWords();
  const fill = (key: string, parts: Record<string, string>) => words[key]!.text.replace(/\{(\w+)\}/g, (_, p: string) => parts[p]!);

  test('a template filled in prints what the window prints', () => {
    expect(fill('delivery.sent_queued', { name: 'Ada' })).toBe(sentRowLine('Ada', true));
    expect(fill('delivery.sent_saved', { name: 'Ada' })).toBe(sentRowLine('Ada', false));
    expect(fill('delivery.reask_waiting', { name: 'Ada' })).toBe(reaskRowLine('Ada', '2026-02-02T00:00:00.000Z', false));
    expect(fill('delivery.reask_saved', { name: 'Ada' })).toBe(reaskRowLine('Ada', null, false));
  });

  test('a template holds for every value of its part, not only the marker it was made with', () => {
    for (const key of Object.keys(words).filter((k) => words[k]!.parts.length)) {
      const word = words[key]!;
      const numeric = word.parts.includes('minutes');
      for (const sample of numeric ? ['0', '1', '2', '17'] : ['Ada', 'Grace Hopper', 'a', '2']) {
        const made = WORD_MAKERS[key]?.(sample);
        if (made === undefined) throw new Error(`no maker for ${key}: add it to WORD_MAKERS`);
        expect(word.text.replace(/\{(\w+)\}/g, sample), `${key} with ${sample}`).toBe(made);
      }
    }
  });

  test('every section has its name', () => {
    for (const { id, label } of INBOX_SECTIONS) expect(words[`section.${id}`]?.text, id).toBe(label);
  });
});
