/**
 * The world of inbox-review-generated.spec.ts: inbox-review-images-world.ts's scratch Inbox (compiled binary, its own
 * HOME and data folder, a fake `gh`), with a teammate's pull request that bumps dependencies (package.json and its
 * package-lock.json) and a tool's yarn.lock alone (a Dependabot-style bump, its package.json left as it is), and an
 * agent's guided review of the same real `git diff`. Every name is invented.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Browser } from '@playwright/test';
import { scratchProject } from '../../scripts/inbox-sim';
import { git, startPullWorld, type ImagesWorld } from './inbox-review-images-world';

export const MANIFEST = 'package.json';
export const LOCK = 'package-lock.json';
export const TOOL_LOCK = 'tools/yarn.lock';

const manifest = (dependencies: Record<string, string>) => `${JSON.stringify({ name: 'web-app', version: '1.4.0', private: true, dependencies }, null, 2)}\n`;
const packageLock = (dependencies: Record<string, string>, installed: Record<string, string>) =>
  `${JSON.stringify(
    {
      name: 'web-app',
      version: '1.4.0',
      lockfileVersion: 3,
      requires: true,
      packages: {
        '': { name: 'web-app', version: '1.4.0', dependencies },
        ...Object.fromEntries(Object.entries(installed).map(([name, version]) => [`node_modules/${name}`, { version, resolved: `https://registry.npmjs.org/${name}/-/${name}-${version}.tgz`, license: 'MIT' }])),
      },
    },
    null,
    2,
  )}\n`;
const yarnLock = (entries: Record<string, string>) =>
  `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n${Object.entries(entries)
    .map(([spec, version]) => {
      const name = spec.slice(0, spec.lastIndexOf('@'));
      return `${spec}:\n  version "${version}"\n  resolved "https://registry.yarnpkg.com/${name}/-/${name}-${version}.tgz"\n`;
    })
    .join('\n')}`;

const BEFORE = { 'date-fns': '^3.6.0', react: '^18.3.1', zod: '^3.23.8' };
const AFTER = { 'date-fns': '^4.1.0', react: '^18.3.1', zod: '^3.24.1', 'tiny-invariant': '^1.3.3' };

function change(parent: string): { project: string; patch: string; head: string; base: string } {
  const project = scratchProject(parent, 'web-app');
  mkdirSync(join(project, 'tools'), { recursive: true });
  writeFileSync(join(project, 'README.md'), 'A scratch project.\n');
  writeFileSync(join(project, MANIFEST), manifest(BEFORE));
  writeFileSync(join(project, LOCK), packageLock(BEFORE, { 'date-fns': '3.6.0', react: '18.3.1', 'loose-envify': '1.4.0', zod: '3.23.8' }));
  writeFileSync(join(project, 'tools/package.json'), `${JSON.stringify({ name: 'tools', private: true, devDependencies: { prettier: '^3.3.0', 'lint-staged': '^15.2.0' } }, null, 2)}\n`);
  writeFileSync(join(project, TOOL_LOCK), yarnLock({ 'prettier@^3.3.0': '3.3.2', 'lint-staged@^15.2.0': '15.2.7' }));
  git(project, 'add', '-A');
  git(project, 'commit', '-q', '-m', 'base');
  writeFileSync(join(project, MANIFEST), manifest(AFTER));
  writeFileSync(join(project, LOCK), packageLock(AFTER, { 'date-fns': '4.1.0', react: '18.3.1', 'loose-envify': '1.4.0', zod: '3.24.1', 'tiny-invariant': '1.3.3' }));
  writeFileSync(join(project, TOOL_LOCK), yarnLock({ 'prettier@^3.3.0': '3.4.2', 'lint-staged@^15.2.0': '15.2.11' }));
  git(project, 'add', '-A');
  git(project, 'commit', '-q', '-m', 'the change');
  git(project, 'remote', 'add', 'origin', 'https://github.com/northwind/web-app.git');
  return { project, patch: git(project, 'diff', '--no-renames', 'HEAD~1', 'HEAD'), head: git(project, 'rev-parse', 'HEAD').trim(), base: git(project, 'rev-parse', 'HEAD~1').trim() };
}

const GUIDE = {
  title: 'Bump the dependencies',
  intent: 'date-fns moves to 4, zod gets a fix, and the tools pick up their patch releases.',
  sections: [
    { title: 'The app', overview: 'A major bump and a new helper.', diffs: [{ file: MANIFEST, summary: 'The new ranges.' }, { file: LOCK, summary: 'What npm resolved.' }] },
    { title: 'The tools', overview: 'A lockfile-only bump.', diffs: [{ file: TOOL_LOCK, summary: 'Patch releases.' }] },
  ],
};

export function startGeneratedWorld(browser: Browser): Promise<ImagesWorld> {
  return startPullWorld(browser, 'plannotator-review-generated-e2e-', change, GUIDE, 'The dependency bump to look at.');
}

